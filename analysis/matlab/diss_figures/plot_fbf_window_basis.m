function drawBar(startSample, endSample, y, height, fillColour, ...
        edgeColour, label)
%DRAWBAR Draw one labelled half-open interval.

    patch( ...
        [startSample, endSample, endSample, startSample], ...
        [y, y, y + height, y + height], ...
        fillColour, ...
        "EdgeColor", edgeColour, ...
        "LineWidth", 2, ...
        "HandleVisibility", "off");
    text(mean([startSample, endSample]), y + height / 2, label, ...
        "Interpreter", "latex", ...
        "HorizontalAlignment", "center", ...
        "VerticalAlignment", "middle", ...
        "FontWeight", "bold", ...
        "Color", edgeColour);
end


function drawExactRange(startSample, endSample, y, colour, label)
%DRAWEXACTRANGE Draw a discrete inclusive range with exact endpoint markers.

    plot([startSample, endSample], [y, y], ...
        "-", ...
        "Color", colour, ...
        "LineWidth", 3, ...
        "HandleVisibility", "off");
    plot([startSample, endSample], [y, y], ...
        "|", ...
        "Color", colour, ...
        "MarkerSize", 18, ...
        "LineWidth", 3, ...
        "HandleVisibility", "off");
    text(mean([startSample, endSample]), y + 0.10, label, ...
        "Interpreter", "latex", ...
        "HorizontalAlignment", "center", ...
        "VerticalAlignment", "bottom", ...
        "FontWeight", "bold", ...
        "Color", colour);
end
