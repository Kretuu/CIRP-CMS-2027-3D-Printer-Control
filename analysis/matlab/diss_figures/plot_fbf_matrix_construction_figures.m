function values = cardinalBspline(degree, sample)
%CARDINALBSPLINE Evaluate the causal cardinal B-spline used by the C code.

    if degree == 0
        values = double(sample >= 0 & sample < 1);
        return;
    end

    values = zeros(size(sample));
    active = sample > 0 & sample < degree + 1;
    activeSample = sample(active);
    values(active) = ...
        (activeSample / degree) ...
        .* cardinalBspline(degree - 1, activeSample) ...
        + ((degree + 1 - activeSample) / degree) ...
        .* cardinalBspline(degree - 1, activeSample - 1);
end


function drawBar(startSample, endSample, y, height, fillColour, ...
        edgeColour)
%DRAWBAR Draw one half-open sample interval.

    patch( ...
        [startSample, endSample, endSample, startSample], ...
        [y, y, y + height, y + height], ...
        fillColour, ...
        "EdgeColor", edgeColour, ...
        "LineWidth", 2, ...
        "HandleVisibility", "off");
end


function drawGroupRange(startSample, endSample, y, colour, label)
%DRAWGROUPRANGE Draw a bracket-like range beneath coefficient markers.

    plot([startSample, endSample], [y, y], ...
        "-", ...
        "Color", colour, ...
        "LineWidth", 3, ...
        "HandleVisibility", "off");
    plot([startSample, endSample], [y, y], ...
        "|", ...
        "Color", colour, ...
        "MarkerSize", 18, ...
        "LineWidth", 3, ...
        "HandleVisibility", "off");
    text(mean([startSample, endSample]), y + 0.12, label, ...
        "Interpreter", "latex", ...
        "HorizontalAlignment", "center", ...
        "VerticalAlignment", "bottom", ...
        "FontWeight", "bold", ...
        "Color", colour);
end


function drawSupportRange(startSample, endSample, y, colour)
%DRAWSUPPORTRANGE Draw a support interval with endpoint markers.

    plot([startSample, endSample], [y, y], ...
        "-", ...
        "Color", colour, ...
        "LineWidth", 4, ...
        "HandleVisibility", "off");
    plot([startSample, endSample], [y, y], ...
        "|", ...
        "Color", colour, ...
        "MarkerSize", 16, ...
        "LineWidth", 2.5, ...
        "HandleVisibility", "off");
end


function drawArrowRange(startSample, endSample, y, colour)
%DRAWARROWRANGE Draw a right-pointing range without using annotations.

    plot([startSample, endSample], [y, y], ...
        "-", ...
        "Color", colour, ...
        "LineWidth", 2.5, ...
        "HandleVisibility", "off");
    plot(endSample, y, ">", ...
        "Color", colour, ...
        "MarkerFaceColor", colour, ...
        "MarkerSize", 7, ...
        "HandleVisibility", "off");
end
