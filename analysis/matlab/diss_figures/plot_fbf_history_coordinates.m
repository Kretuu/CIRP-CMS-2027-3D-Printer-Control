clear;
close all;
clc;

% Show how one fixed matrix row is evaluated across basis columns.
columnValues = [0:10, NaN, 20];
basisIndices = [-7:3, NaN, 13];
basisStarts = basisIndices * 10;
basisInputs = -basisStarts; % k - iL for the fixed sample k = 0.

columnCount = numel(columnValues);
rowCount = 4;

figure( ...
    "Units", "centimeters", ...
    "Position", [2, 2, 21, 7.8], ...
    "Color", "white", ...
    "ToolBar", "none");
hold on;

historyFill = [0.84, 0.90, 0.98];
historyEdge = [0.25, 0.45, 0.72];
currentFill = [0.83, 0.95, 0.85];
currentEdge = [0.20, 0.53, 0.29];
ellipsisFill = [0.94, 0.94, 0.94];

for column = 1:columnCount
    if isnan(basisIndices(column))
        fillColour = ellipsisFill;
        edgeColour = [0.55, 0.55, 0.55];
    elseif basisIndices(column) < 0
        fillColour = historyFill;
        edgeColour = historyEdge;
    else
        fillColour = currentFill;
        edgeColour = currentEdge;
    end

    for row = 1:rowCount
        patch( ...
            [column - 1, column, column, column - 1], ...
            [row - 1, row - 1, row, row], ...
            fillColour, ...
            "EdgeColor", edgeColour, ...
            "LineWidth", 1.5, ...
            "HandleVisibility", "off");
    end
end

rowLabels = { ...
    "input \(k-iL\)", ...
    "basis start \(iL\)", ...
    "basis index \(i\)", ...
    "column \(c\)"};
for row = 1:rowCount
    text(-0.25, row - 0.5, rowLabels{row}, ...
        "Interpreter", "latex", ...
        "HorizontalAlignment", "right", ...
        "VerticalAlignment", "middle", ...
        "FontWeight", "bold");
end

for column = 1:columnCount
    if isnan(columnValues(column))
        values = {"\(\cdots\)", "\(\cdots\)", "\(\cdots\)", "\(\cdots\)"};
    else
        values = { ...
            sprintf("%d", basisInputs(column)), ...
            sprintf("%d", basisStarts(column)), ...
            sprintf("%d", basisIndices(column)), ...
            sprintf("%d", columnValues(column))};
    end

    for row = 1:rowCount
        if row == 1 && ~isnan(basisInputs(column)) ...
                && basisInputs(column) < 0
            textColour = [0.70, 0.12, 0.10];
        else
            textColour = [0.12, 0.12, 0.12];
        end
        text(column - 0.5, row - 0.5, values{row}, ...
            "Interpreter", "latex", ...
            "HorizontalAlignment", "center", ...
            "VerticalAlignment", "middle", ...
            "FontWeight", "bold", ...
            "Color", textColour);
    end
end

text(3.5, 4.28, ...
    "historical basis columns", ...
    "HorizontalAlignment", "center", ...
    "VerticalAlignment", "bottom", ...
    "FontWeight", "bold", ...
    "Color", historyEdge);
text(10, 4.28, ...
    "current basis columns", ...
    "HorizontalAlignment", "center", ...
    "VerticalAlignment", "bottom", ...
    "FontWeight", "bold", ...
    "Color", currentEdge);

xlim([-3.5, columnCount]);
ylim([-0.12, 4.70]);
axis off;
fontsize(gcf, 14, "points");

scriptDirectory = fileparts(mfilename("fullpath"));
outputPath = fullfile( ...
    scriptDirectory, ...
    "fbf-history-coordinates.png");
exportgraphics(gcf, outputPath, "Resolution", 300);
close(gcf);
